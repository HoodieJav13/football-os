// Writes the deterministic FICTIONAL fixtures and a summary table.
// Run: node tools/export-fixtures.mjs
// Output: fixtures/<scenario>-seed<seed>.json (canonical seeds) and
//         fixtures/summary.json + fixtures/FIXTURES.md (every scenario x seed).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateFixture, SCENARIOS, FIXTURE_SEEDS } from '../src/domain/fixtures.js';
import { computeSchedule } from '../src/domain/week.js';
import { generateRotation } from '../src/domain/rotation.js';
import { exportProject, validateProject } from '../src/domain/project.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'fixtures');
const library = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/library.json'), 'utf8'));
fs.mkdirSync(OUT, { recursive: true });

const CANONICAL = { example: 42, normal: 7, thin: 7, unavailable: 7, 'shared-group': 7, locks: 7, renamed: 7 };
const rows = [];
for (const scenario of SCENARIOS) {
  for (const seed of FIXTURE_SEEDS) {
    const p = generateFixture({ seed, scenario, library });
    const errors = validateProject(p).errors.length;
    let shortages = 0, problems = 0, repeats = 0, unavoidable = 0, slots = 0, locked = 0, groupOverlaps = 0, overDays = 0;
    for (const d of p.week.days) {
      const s = computeSchedule(d);
      if (s.overByMin) overDays++;
      groupOverlaps += s.warnings.filter((w) => w.type === 'group-overlap').length;
      const r = generateRotation({ day: d, groups: p.groups, participants: p.participants, previous: p.rotations[d.id] || null, seed });
      slots += r.constraints.slotCount;
      locked += r.constraints.lockedCount;
      shortages += r.warnings.filter((w) => w.type === 'shortage').length;
      problems += r.warnings.filter((w) => w.severity === 'error').length;
      const rep = r.warnings.filter((w) => w.type === 'repeat-role');
      repeats += rep.length;
      unavoidable += rep.filter((w) => w.unavoidable).length;
    }
    rows.push({
      scenario, seed, participants: p.participants.length, days: p.week.days.length,
      periods: p.week.days.reduce((a, d) => a + d.periods.length, 0), validationErrors: errors,
      slots, locked, shortages, problems, repeats, unavoidableRepeats: unavoidable, groupOverlaps, overDays,
      unavailableMarks: p.participants.reduce((a, x) => a + x.unavailable.length, 0),
    });
    if (CANONICAL[scenario] === seed) fs.writeFileSync(path.join(OUT, `${scenario}-seed${seed}.json`), exportProject(p, null));
  }
}
fs.writeFileSync(path.join(OUT, 'summary.json'), `${JSON.stringify(rows, null, 2)}\n`);
const head = '| scenario | seed | participants | days | periods | slots | locked | unfilled | problems | repeats (unavoidable) | group overlaps | unavailable marks | validation errors |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n';
const body = rows.map((r) => `| ${r.scenario} | ${r.seed} | ${r.participants} | ${r.days} | ${r.periods} | ${r.slots} | ${r.locked} | ${r.shortages} | ${r.problems} | ${r.repeats} (${r.unavoidableRepeats}) | ${r.groupOverlaps} | ${r.unavailableMarks} | ${r.validationErrors} |`).join('\n');
fs.writeFileSync(path.join(OUT, 'FIXTURES.md'), `# Fictional fixtures

Generated by \`node tools/export-fixtures.mjs\` from \`src/domain/fixtures.js\` and
\`content/library.json\`. Everything is FICTIONAL: synthetic "Fict Scout NN" labels,
scout roles and groups only — no names, health or identity fields, no real roster.

Rotation numbers below come from generating every day with the fixture's own seed
(locks from the \`locks\` scenario are kept). "Problems" are errors such as an
invalid lock; a clean generation has none. Repeats are informational.

Canonical JSON files: ${Object.entries(CANONICAL).map(([s, n]) => `\`${s}-seed${n}.json\``).join(', ')}.

${head}${body}
`);
console.log(`wrote ${rows.length} rows, ${Object.keys(CANONICAL).length} fixture files to fixtures/`);
